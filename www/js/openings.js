/**
 * SAN 배열 → [이름(ECO 포함), 정석으로 인정한 수 개수]
 * 가장 길게 맞는 수순을 고른다.
 */
export function findOpening(sans) {
  let bestName = '오프닝 불명';
  let bestLen = 0;
  for (const [eco, name, seq] of OPENINGS) {
    const toks = seq.split(' ');
    if (toks.length > sans.length || toks.length <= bestLen) continue;
    let ok = true;
    for (let i = 0; i < toks.length; i++) {
      if (sans[i] !== toks[i]) { ok = false; break; }
    }
    if (ok) { bestName = `${eco} ${name}`; bestLen = toks.length; }
  }
  return [bestName, bestLen];
}
